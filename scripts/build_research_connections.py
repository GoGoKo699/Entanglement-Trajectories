#!/usr/bin/env python3
"""Render the research-question guide from its source-specific discovery registry."""
from __future__ import annotations

import argparse
import json
from pathlib import Path, PurePosixPath
from typing import Any
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = "metadata/research_connections.json"
OUTPUT = "docs/RESEARCH_CONNECTIONS.md"


def validate(data: dict[str, Any]) -> None:
    """Check internal identifiers and safe navigation without external requests."""
    if data.get("schema_version") != "1.0.0":
        raise ValueError("Unsupported research-connections schema")
    if data.get("canonical_repository") != "https://github.com/GoGoKo699/Entanglement-Trajectories":
        raise ValueError("Unexpected repository")
    for collection in ("works", "neighbors", "questions"):
        rows = data.get(collection)
        if not isinstance(rows, list) or not rows:
            raise ValueError(f"Missing or empty collection: {collection}")
        ids = [row["id"] for row in rows]
        if len(ids) != len(set(ids)):
            raise ValueError(f"Duplicate identifier in {collection}")
    work_ids = {row["id"] for row in data["works"]}
    if work_ids != {"analytical_note", "trajectory_paper", "repository"}:
        raise ValueError("The three reference targets must remain distinct")
    neighbor_ids = {row["id"] for row in data["neighbors"]}
    for row in data["works"] + data["neighbors"]:
        parsed = urlparse(row["url"])
        if parsed.scheme != "https" or not parsed.netloc:
            raise ValueError(f"Expected HTTPS primary link: {row['id']}")
    for row in data["questions"]:
        for key in ("question", "answer", "scope"):
            if not isinstance(row.get(key), str) or not row[key].strip():
                raise ValueError(f"Missing {key}: {row['id']}")
        if not row["sources"] or not set(row["sources"]).issubset(work_ids):
            raise ValueError(f"Unknown source for {row['id']}")
        if not set(row["neighbors"]).issubset(neighbor_ids):
            raise ValueError(f"Unknown neighbor for {row['id']}")
        for link in row["reading"]:
            path = PurePosixPath(link["path"])
            if path.is_absolute() or ".." in path.parts or ":" in link["path"]:
                raise ValueError(f"Invalid repository path: {link['path']}")


def render(data: dict[str, Any]) -> str:
    """Produce a deterministic human-readable page from the registry."""
    validate(data)
    works = {row["id"]: row for row in data["works"]}
    neighbors = {row["id"]: row for row in data["neighbors"]}
    labels = {
        "analytical_note": "Analytical note — arXiv:2204.01754",
        "trajectory_paper": "Trajectory paper — Quantum 8, 1282",
        "repository": "Versioned repository",
    }
    lines = [
        "<!-- Generated by scripts/build_research_connections.py; edit metadata/research_connections.json. -->",
        f"# {data['title']}", "", data["purpose"], "", data["relationship_policy"], "",
        "## Three distinct sources", "", data["source_distinction"], "",
    ]
    for row in data["works"]:
        lines.extend([
            f"### {labels[row['id']]}", "",
            f"**[{row['title']}]({row['url']})** — {row['identifier']}.", "",
            row["scope"], "", f"**Source selection.** {row['citation_use']}", "",
        ])
    lines.extend([
        "## Research questions", "",
        "Each connection below identifies a mathematical or scientific reason to read the sources together. Established identities and majorization tools are distinguished from this project’s specific use of them.", "",
    ])
    for row in data["questions"]:
        lines.extend([
            f"<a id=\"{row['id']}\"></a>", f"### {row['question']}", "",
            row["answer"], "", row["scope"], "",
            "**Relevant source:** " + "; ".join(f"[{labels[item]}]({works[item]['url']})" for item in row["sources"]) + ".", "",
        ])
        if row["reading"]:
            lines.extend(["**Repository reading:** " + "; ".join(f"[{link['label']}](../{link['path']})" for link in row["reading"]) + ".", ""])
        lines.extend(["**Related reading:** " + "; ".join(f"[{neighbors[item]['title']}]({neighbors[item]['url']})" for item in row["neighbors"]) + ".", ""])
    lines.extend(["## Related literature", "", "Years below distinguish first preprint appearance from subsequent journal publication.", ""])
    for row in data["neighbors"]:
        authors = ", ".join(row["authors"])
        publication = f" {row['publication']}." if row.get("publication") else ""
        lines.extend([
            f"**{authors}. [{row['title']}]({row['url']}).** First public year: {row['first_public_year']}.{publication}", "",
            row["connection"], "",
        ])
    lines.extend([
        "The [foundational conceptual-neighbor map](CONCEPTUAL_NEIGHBORS.md) covers earlier spectrum, majorization and multi-Rényi literature. The [correction summary](../CORRECTIONS.md) and [public claim registry](../metadata/public_claims.json) retain their scientific authority.", "",
        "The [structured question and source index](../metadata/research_connections.json) records the same connections for programmatic reading.", "",
    ])
    return "\n".join(lines).rstrip() + "\n"


def build(root: Path = ROOT, *, check: bool = False) -> Path:
    data = json.loads((root / REGISTRY).read_text(encoding="utf-8"))
    text = render(data)
    destination = root / OUTPUT
    if check:
        if not destination.is_file() or destination.read_text(encoding="utf-8") != text:
            raise ValueError("Research-question guide is stale; run make public-context")
    else:
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(text, encoding="utf-8")
    return destination


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check the generated page without writing it")
    args = parser.parse_args()
    path = build(check=args.check)
    print(f"{'Verified' if args.check else 'Wrote'} {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
